"""Exhaustive small-order PD selection truth from independent descendant facts.

No implementation source, third-party dependency, old-generator replay or fetch.
"""
from fractions import Fraction
from pathlib import Path
import hashlib
import itertools
import json
import struct

ROOT = Path(__file__).resolve().parents[1]

def bits(value):
    return struct.pack('>d', float(value)).hex()

def strings(values):
    return '[' + ', '.join(json.dumps(x, ensure_ascii=False) for x in values) + ']'

def newly_covered(full, old, new):
    return [e for e in full['edges'] if new.intersection(e['descendant_taxa'])
            and not old.intersection(e['descendant_taxa'])]

def total(edges):
    return sum((Fraction.from_float(e['length']) for e in edges), Fraction(0))

def reference(name, full, baseline, candidates, limit):
    base = set(baseline)
    eligible = sorted(set(candidates) - base)
    count = min(limit, len(eligible))
    evaluated = []
    for order in itertools.permutations(eligible, count):
        old, steps, key = set(base), [], []
        for taxon in order:
            edges = newly_covered(full, old, {taxon})
            exact = total(edges)
            key.append((-exact, taxon))
            steps.append({'taxon': taxon, 'gain_bits': bits(exact), 'exact_gain': str(exact), 'edges': edges})
            old.add(taxon)
        evaluated.append((tuple(key), order, steps))
    # Lexicographically best (negative exact gain, taxon) sequence enforces the
    # per-step rule by exhaustively comparing complete candidate orders.
    _, order, steps = min(evaluated, key=lambda item: item[0])
    exact = total(newly_covered(full, base, set(order)))
    optimum = max(total(newly_covered(full, base, set(choice)))
                  for choice in itertools.combinations(eligible, count))
    return {'name': name, 'newick': full['newick'], 'baseline': baseline,
            'candidates': candidates, 'limit': limit, 'order': list(order), 'steps': steps,
            'gain_bits': bits(exact), 'exact_gain': str(exact), 'exhaustive_optimum': str(optimum),
            'matches_bounded_optimum': exact == optimum, 'orders_enumerated': len(evaluated)}

def main():
    source = ROOT / 'testdata/diversity-golden.json'
    original = json.loads(source.read_text(encoding='utf-8'))
    rows = {x['name']: x for x in original['fixtures']}
    cases = []
    sets = [[x for bit, x in enumerate('ABCD') if mask & (1 << bit)] for mask in range(16)]
    for index, baseline in enumerate(sets):
        for limit in range(5):
            cases.append(reference(f'base-{index}-limit-{limit}', rows['small-0-subset-15'], baseline, list('ABCD'), limit))
    for topology in (1, 2):
        for index, baseline in enumerate([[], ['A', 'C']]):
            for limit in range(5):
                cases.append(reference(f'topology-{topology}-{index}-{limit}', rows[f'small-{topology}-subset-15'], baseline, list('ABCD'), limit))
    real = rows['real-all']; taxa = real['present']
    scenarios = [([], taxa[:8], 3), (taxa[:6], taxa[4:12], 3),
                 (taxa[::4], taxa[:8], 2), (taxa, taxa[:8], 3)]
    for index, (baseline, candidates, limit) in enumerate(scenarios):
        cases.append(reference(f'real-{index}', real, baseline, candidates, limit))
    numeric = [
        {'newick': '(A:10000000000000000,(B:10000000000000000):1)R;',
         'edges': [{'descendant_taxa': ['A'], 'length': 1e16}, {'descendant_taxa': ['B'], 'length': 1.0}, {'descendant_taxa': ['B'], 'length': 1e16}]},
        {'newick': '(A:10000000000000000,B:1,C:1)R;',
         'edges': [{'descendant_taxa': ['A'], 'length': 1e16}, {'descendant_taxa': ['B'], 'length': 1.0}, {'descendant_taxa': ['C'], 'length': 1.0}]},
    ]
    cases.append(reference('exact-comparison', numeric[0], [], ['A', 'B'], 1))
    cases.append(reference('aggregate-rounding', numeric[1], [], ['A', 'B', 'C'], 3))
    output = {'reference': {'source': 'testdata/diversity-golden.json', 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
              'method': 'enumerate candidate orders with exact Fraction/descendant-edge facts; separately enumerate final subsets'}, 'fixtures': cases}
    (ROOT / 'testdata/diversity-greedy-golden.json').write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    lines = ['// Generated by exhaustive independent Fraction order/subset enumeration.', '///|',
             'test "PD greedy independent 106 exhaustive order and edge cases" {']
    for row in cases:
        steps = []
        for step in row['steps']:
            edges = '[' + ', '.join('(' + strings(e['descendant_taxa']) + ', 0x' + bits(e['length']) + 'UL.reinterpret_as_double())' for e in step['edges']) + ']'
            steps.append('(' + json.dumps(step['taxon'], ensure_ascii=False) + ', 0x' + step['gain_bits'] + 'UL, ' + edges + ')')
        lines.append('  check_pd_greedy(read(' + json.dumps(row['newick'], ensure_ascii=False) + '), ' + strings(row['baseline']) + ', ' + strings(row['candidates']) + ', ' + str(row['limit']) + 'U, ' + strings(row['order']) + ', 0x' + row['gain_bits'] + 'UL, [' + ', '.join(steps) + '])')
    lines += ['}', '']
    (ROOT / 'diversity_greedy_oracle_test.mbt').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({'cases': len(cases), 'real_cases': 4, 'bounded_optima_matched': sum(x['matches_bounded_optimum'] for x in cases),
                      'orders_enumerated': sum(x['orders_enumerated'] for x in cases), 'old_generators_replayed': False}))

if __name__ == '__main__':
    main()
