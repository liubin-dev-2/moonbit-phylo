"""Independent Faith PD fixtures only; never regenerate the old RF/Fitch corpus.

Use the pinned verification requirements. Biopython supplies tree parsing and
descendant sets; Fraction sums the exact values of parsed binary64 edge lengths.
No MoonBit implementation source is read. Run from any working directory.
"""
from fractions import Fraction
from pathlib import Path
import hashlib
import io
import json
import struct

import Bio
from Bio import Phylo

ROOT = Path(__file__).resolve().parents[1]


def bit_pattern(value):
    return struct.pack('>d', value).hex()


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def strings(values):
    return '[' + ', '.join(map(quoted, values)) + ']'


def literal(value):
    return '0x' + bit_pattern(value) + 'UL.reinterpret_as_double()'


def reference(name, text, present):
    tree = Phylo.read(io.StringIO(text), 'newick')
    observed = set(present)
    edges = []
    total = Fraction(0)
    for clade in tree.find_clades(order='preorder'):
        if clade is tree.root:
            continue
        descendants = sorted(x.name for x in clade.get_terminals())
        if observed.intersection(descendants):
            assert clade.branch_length is not None
            value = float(clade.branch_length)
            total += Fraction.from_float(value)
            edges.append({'descendant_taxa': descendants, 'length': value})
    return {'name': name, 'newick': text, 'present': present, 'edges': edges,
            'exact_total': str(total), 'total_bits': bit_pattern(float(total))}


def main():
    fixtures = []
    small = [
        '((A:1,B:2):3,(C:4,D:5):6):999;',
        '((A:0,B:0):2,C:3,D:4);',
        '((((A:1):2):3,B:4):9,(C:5,D:6):7):8;',
    ]
    for index, text in enumerate(small):
        for mask in range(16):
            present = [label for bit, label in enumerate('ABCD') if mask & (1 << bit)]
            fixtures.append(reference(f'small-{index}-subset-{mask}', text, present))
    real_path = ROOT / 'testdata/fiddler-42.newick'
    text = real_path.read_text(encoding='utf-8').strip()
    real = Phylo.read(io.StringIO(text), 'newick')
    taxa = sorted(x.name for x in real.get_terminals())
    assert len(taxa) == 42
    for name, present in [('empty', []), ('singleton', taxa[:1]), ('six', taxa[:6]),
                          ('every-fourth', taxa[::4]), ('all', taxa)]:
        fixtures.append(reference('real-' + name, text, present))
    output = {'reference': {'biopython': Bio.__version__,
                           'definition': 'https://scikit.bio/docs/latest/generated/skbio.diversity.alpha.faith_pd.html',
                           'method': 'nonroot edges whose descendant tip set intersects selected taxa; exact Fraction.from_float sum',
                           'real_input_sha256': hashlib.sha256(real_path.read_bytes()).hexdigest()},
              'fixtures': fixtures}
    (ROOT / 'testdata/diversity-golden.json').write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    lines = ['// Generated by verification/diversity_reference.py using Biopython/Fraction.', '///|',
             'test "faith PD independent descendant-set oracle on 53 subset and real communities" {',
             '  let cases : Array[(String, Array[String], UInt64, Array[(Array[String], Double)])] = [']
    for case in fixtures:
        edges = '[' + ', '.join('(' + strings(e['descendant_taxa']) + ', ' + literal(e['length']) + ')' for e in case['edges']) + ']'
        lines.append('    (' + quoted(case['newick']) + ', ' + strings(case['present']) + ', 0x' + case['total_bits'] + 'UL, ' + edges + '),')
    lines += ['  ]', '  for (text, present, expected, edges) in cases {',
              '    check_pd(read(text), present, expected, edges)', '  }', '}', '']
    (ROOT / 'diversity_oracle_test.mbt').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({'biopython': Bio.__version__, 'independent_cases': len(fixtures),
                      'small_subsets': 48, 'real_communities': 5, 'real_taxa': len(taxa)}))


if __name__ == '__main__':
    main()
